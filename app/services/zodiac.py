def sign_for(date: dt.date) -> str:
    """Знак зодиака по дате рождения."""
    # Идём от конца списка: берём первую границу, которую дата уже прошла.
    for month, day, name in reversed(_SIGNS):
        if (date.month, date.day) >= (month, day):
            return name
    # Раньше 20 января — Козерог (он начинается в декабре).
    return "Козерог"


def with_emoji(sign: str) -> str:
    return f"{EMOJI.get(sign, '')} {sign}".strip()


def element_for(sign: str) -> str:
    return ELEMENTS.get(sign, "")
