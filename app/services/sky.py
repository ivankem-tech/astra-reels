def moon_longitude(t: float) -> float:
    """Эклиптическая долгота Луны в градусах."""
    lp = _norm(218.3164477 + 481267.88123421 * t - 0.0015786 * t * t
               + t ** 3 / 538841 - t ** 4 / 65194000)
    d = _norm(297.8501921 + 445267.1114034 * t - 0.0018819 * t * t
              + t ** 3 / 545868 - t ** 4 / 113065000)
    m = _norm(357.5291092 + 35999.0502909 * t - 0.0001536 * t * t
              + t ** 3 / 24490000)
    mp = _norm(134.9633964 + 477198.8675055 * t + 0.0087414 * t * t
               + t ** 3 / 69699 - t ** 4 / 14712000)
    f = _norm(93.2720950 + 483202.0175233 * t - 0.0036539 * t * t
              - t ** 3 / 3526000 + t ** 4 / 863310000)
    # эксцентриситет орбиты Земли: члены с M ослабевают со временем
    e = 1 - 0.002516 * t - 0.0000074 * t * t

    total = 0.0
    for cd, cm, cmp_, cf, coef in _MOON_TERMS:
        arg = (cd * d + cm * m + cmp_ * mp + cf * f) * RAD
        factor = e ** abs(cm)
        total += coef * factor * math.sin(arg)

    return _norm(lp + total / 1_000_000)


