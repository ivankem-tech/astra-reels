"""Положения светил: Солнце, Луна, планеты, асцендент и дома.

Тот же путь, которым в events.py сделаны фазы луны: короткие ряды из
Мееуса вместо внешней библиотеки. Причина простая — так каждую цифру
можно проверить прямо здесь и сверить с опубликованными эфемеридами,
а не надеяться, что чужой пакет соберётся на Render.

Точность — угловые минуты. Знак зодиака шириной тридцать градусов,
так что запас огромный; на границе знака отмечаем это отдельно.
"""
from __future__ import annotations

import datetime as dt
import math
from dataclasses import dataclass

TAU = 2 * math.pi
RAD = math.pi / 180


def _norm(deg: float) -> float:
    return deg % 360.0


def julian_day(moment: dt.datetime) -> float:
    """Юлианская дата для момента в UTC."""
    y, m = moment.year, moment.month
    d = (moment.day + moment.hour / 24 + moment.minute / 1440
         + moment.second / 86400)
    if m <= 2:
        y -= 1
        m += 12
    a = y // 100
    b = 2 - a + a // 4                      # григорианская поправка
    return (math.floor(365.25 * (y + 4716)) + math.floor(30.6001 * (m + 1))
            + d + b - 1524.5)


def centuries(jd: float) -> float:
    """Юлианские столетия от эпохи J2000."""
    return (jd - 2451545.0) / 36525.0


# ======================= наклон эклиптики =======================

def obliquity(t: float) -> float:
    """Наклон эклиптики к экватору, в градусах (Мееус, гл. 22)."""
    return (23.439291
            - 0.0130042 * t
            - 1.64e-7 * t * t
            + 5.036e-7 * t ** 3)


# ======================= Солнце =======================

def sun_longitude(t: float) -> float:
    """Видимая эклиптическая долгота Солнца (Мееус, гл. 25)."""
    l0 = 280.46646 + 36000.76983 * t + 0.0003032 * t * t
    m = 357.52911 + 35999.05029 * t - 0.0001537 * t * t
    mr = m * RAD
    c = ((1.914602 - 0.004817 * t - 0.000014 * t * t) * math.sin(mr)
         + (0.019993 - 0.000101 * t) * math.sin(2 * mr)
         + 0.000289 * math.sin(3 * mr))
    true_long = l0 + c
    # переход к видимой долготе: нутация и аберрация
    omega = 125.04 - 1934.136 * t
    return _norm(true_long - 0.00569 - 0.00478 * math.sin(omega * RAD))


