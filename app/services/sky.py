def _heliocentric(name: str, t: float) -> tuple[float, float, float]:
    """Гелиоцентрические прямоугольные координаты в плоскости эклиптики."""
    el = _PLANETS[name]
    a = el.a + el.a_dot * t
    e = el.e + el.e_dot * t
    i = (el.i + el.i_dot * t) * RAD
    l = el.l + el.l_dot * t
    peri = el.peri + el.peri_dot * t
    node = el.node + el.node_dot * t

    m = _norm(l - peri)
    if m > 180:
        m -= 360
    mr = m * RAD

    # уравнение Кеплера, решаем итерациями Ньютона
    ecc = mr + e * math.sin(mr)
    for _ in range(12):
        d = (ecc - e * math.sin(ecc) - mr) / (1 - e * math.cos(ecc))
        ecc -= d
        if abs(d) < 1e-12:
            break

    # координаты в плоскости орбиты
    xv = a * (math.cos(ecc) - e)
    yv = a * math.sqrt(1 - e * e) * math.sin(ecc)

    arg_peri = (peri - node) * RAD
    node_r = node * RAD
    v = math.atan2(yv, xv) + arg_peri
    r = math.hypot(xv, yv)

    x = r * (math.cos(node_r) * math.cos(v)
             - math.sin(node_r) * math.sin(v) * math.cos(i))
    y = r * (math.sin(node_r) * math.cos(v)
             + math.cos(node_r) * math.sin(v) * math.cos(i))
    z = r * math.sin(v) * math.sin(i)
    return x, y, z


def planet_longitude(name: str, t: float) -> float:
    """Геоцентрическая эклиптическая долгота планеты."""
    px, py, pz = _heliocentric(name, t)
    ex, ey, ez = _heliocentric("Земля", t)
    return _norm(math.degrees(math.atan2(py - ey, px - ex)))


# ======================= звёздное время, асцендент, дома =======================

def sidereal_time(jd: float) -> float:
    """Среднее звёздное время в Гринвиче, в градусах (Мееус, гл. 12)."""
    t = centuries(jd)
    theta = (280.46061837 + 360.98564736629 * (jd - 2451545.0)
             + 0.000387933 * t * t - t ** 3 / 38710000)
    return _norm(theta)


def ascendant(jd: float, lat: float, lon: float) -> float:
    """Асцендент: градус эклиптики, восходящий над горизонтом."""
    lst = _norm(sidereal_time(jd) + lon) * RAD        # местное звёздное время
    eps = obliquity(centuries(jd)) * RAD
    phi = lat * RAD
    # Знак здесь легко перепутать и получить десцендент — точку, которая
    # ровно в этот момент заходит. Ошибка выглядит правдоподобно, поэтому
    # проверяется физикой: на восходе Солнце обязано стоять на асценденте.
    y = math.cos(lst)
    x = -(math.sin(lst) * math.cos(eps) + math.tan(phi) * math.sin(eps))
    return _norm(math.degrees(math.atan2(y, x)))


def midheaven(jd: float, lon: float) -> float:
    """Середина неба: градус эклиптики в верхней кульминации."""
    lst = _norm(sidereal_time(jd) + lon) * RAD
    eps = obliquity(centuries(jd)) * RAD
    return _norm(math.degrees(math.atan2(math.sin(lst),
                                         math.cos(lst) * math.cos(eps))))


# ======================= дома по Плацидусу =======================
#
# Плацидус берём не готовой формулой, а прямо из определения: точка
# эклиптики восходит при часовом угле −SD и кульминирует при 0, где
# SD — её полусуточная дуга. Куспиды 11 и 12 делят этот путь на три
# равных по времени части, куспиды 2 и 3 — так же, но под горизонтом.
#
# Так надёжнее: в закрытых формулах легко перепутать знак и получить
# правдоподобный, но неверный дом. А определение проверяется прямым
# моделированием — что и сделано в тестах.

def _ra_dec(lon_ecl: float, eps: float) -> tuple[float, float]:
    """Прямое восхождение и склонение точки эклиптики (широта нулевая)."""
    l = lon_ecl * RAD
    ra = math.atan2(math.sin(l) * math.cos(eps), math.cos(l))
    dec = math.asin(math.sin(eps) * math.sin(l))
    return _norm(math.degrees(ra)), math.degrees(dec)


def _semi_arc(dec: float, lat: float) -> float:
    """Полусуточная дуга в градусах: от восхода до кульминации."""
    v = -math.tan(lat * RAD) * math.tan(dec * RAD)
    if v <= -1:
        return 180.0          # незаходящая точка
    if v >= 1:
        return 0.0            # невосходящая точка
    return math.degrees(math.acos(v))


def _hour_angle(lon_ecl: float, ramc: float, eps: float) -> float:
    """Часовой угол точки эклиптики, приведённый к −180…180."""
    ra, _ = _ra_dec(lon_ecl, eps)
    return (ramc - ra + 180) % 360 - 180


def _solve_cusp(target, ramc: float, lat: float, eps: float,
                start: float) -> float:
    """Ищет долготу, при которой часовой угол равен заданной доле дуги.

    target(SD) возвращает нужный часовой угол по полусуточной дуге.
    Обычный поиск нуля делением отрезка: функция монотонна на дуге
    в 120°, которой заведомо хватает, чтобы охватить куспид.
    """
    def f(lon: float) -> float:
        _, dec = _ra_dec(lon, eps)
        sd = _semi_arc(dec, lat)
        return (_hour_angle(lon, ramc, eps) - target(sd) + 180) % 360 - 180

    lo, hi = start - 60.0, start + 60.0
    flo, fhi = f(lo), f(hi)
    if flo * fhi > 0:                      # редкий случай у полярных широт
        return _norm(start)
    for _ in range(80):
        mid = (lo + hi) / 2
        fm = f(mid)
        if flo * fm <= 0:
            hi, fhi = mid, fm
        else:
            lo, flo = mid, fm
    return _norm((lo + hi) / 2)


def houses(jd: float, lat: float, lon: float) -> list[float]:
    """Двенадцать куспидов по Плацидусу, начиная с первого дома."""
    eps = obliquity(centuries(jd)) * RAD
    ramc = _norm(sidereal_time(jd) + lon)
    asc = ascendant(jd, lat, lon)
    mc = midheaven(jd, lon)

    # 11 и 12 — между серединой неба и асцендентом, над горизонтом
    c11 = _solve_cusp(lambda sd: -sd / 3, ramc, lat, eps, mc + 30)
    c12 = _solve_cusp(lambda sd: -2 * sd / 3, ramc, lat, eps, mc + 60)
    # 2 и 3 — между асцендентом и глубиной неба, под горизонтом
    c2 = _solve_cusp(lambda sd: -sd - (180 - sd) / 3, ramc, lat, eps, asc + 30)
    c3 = _solve_cusp(lambda sd: -sd - 2 * (180 - sd) / 3, ramc, lat, eps, asc + 60)

    first = [asc, c2, c3, _norm(mc + 180), _norm(c11 + 180), _norm(c12 + 180)]
    return first + [_norm(c + 180) for c in first]
